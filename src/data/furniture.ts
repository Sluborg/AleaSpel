  id: string;
  name: string;
  shape: PlaceholderShape;
  width: number;
  height: number;
  color: number;
  // Default position in room coordinates (design resolution).
  defaultX: number;
  defaultY: number;
  price?: number; // medals in Butiken; no price = free from the start
